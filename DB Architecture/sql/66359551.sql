LEFT OUTER JOIN APPOINTMENT_SCHEDULE aps ON aps.INTERNAL_RECEIPT_NUM = rh.INTERNAL_RECEIPT_NUM
LEFT OUTER JOIN IMMEDIATE_NEEDS_REQUEST IMD ON rd.ITEM=IMD.ITEM and ISNULL(rd.COMPANY,N'<literal:6>')= ISNULL(IMD.COMPANY,N'<literal:7>') AND ISNULL(INTERNAL_FULFILLMENT_NUM,0)  = 0
LEFT OUTER JOIN PURCHASE_ORDER_DETAIL PD ON PD.OBJECT_ID = RD.PURCHASE_ORDER_DETAIL_ID
LEFT OUTER JOIN RECEIPT_CONTAINER rc ON rc.INTERNAL_RECEIPT_NUM=rh.INTERNAL_RECEIPT_NUM
and rc.INTERNAL_RECEIPT_LINE_NUM = rd.INTERNAL_RECEIPT_LINE_NUM;
