	(SELECT gen.DESCRIPTION FROM GENERIC_CONFIG_DETAIL gen where gen.IDENTIFIER =rh.SOURCE_COUNTRY AND gen.RECORD_TYPE = N'<literal:5>') AS RECEIPT_HEADER_COUNTRY,
