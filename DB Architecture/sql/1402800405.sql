	ITEM,
	ITEM_DESC,
	FROM_QTY,
	QUANTITY,
	TO_QTY,
	QUANTITY_UM,
	TOTAL_WEIGHT,
	WEIGHT_UM,
	TOTAL_VOLUME,
	FROM_WHS,
	TO_WHS,
	VOLUME_UM,
	TOTAL_VALUE,
	FROM_LOC,
	TO_LOC,
	FROM_CHECK_DIG,
