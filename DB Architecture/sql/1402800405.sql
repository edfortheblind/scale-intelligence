	OUTGOING_PD_LOC,
	INCOMING_PD_LOC,
	INVENTORY_AT_PD,
	CYCLE_COUNT_GROUP_NUM,
	ASSIGNMENT_ID,
	LOGISTICS_UNIT,
	PARENT_LOGISTICS_UNIT,
	TREE_UNIT,
	TREE_UNIT_ID,
	LOCKED,
	SRC_IDENTIFIER)  
(SELECT WI.INTERNAL_INSTRUCTION_NUM  
      ,WI.INSTRUCTION_TYPE  
      ,WI.PARENT_INSTR  
      ,WI.WORK_UNIT  
      ,WI.SEQUENCE  
      ,WI.LAUNCH_NUM  
      ,WI.PRIORITY  
      ,WI.CONDITION  
