	FROM 
		SHIPMENT_HEADER SH 
		INNER JOIN WORK_INSTRUCTION WI 
			ON (SH.INTERNAL_SHIPMENT_NUM = WI.INTERNAL_NUM AND WI.INTERNAL_NUM_TYPE IN (N'<literal:6>', N'<literal:7>') AND WI.CONDITION = N'<literal:8>')
