CREATE VIEW METADATA_INSIGHT_PURCHASE_ORDER_HEADER_VIEW
AS
SELECT
PH.OBJECT_ID AS POHEADEROBJECTID,
PH.PURCHASE_ORDER_ID AS POHEADERPURCHASEORDERID,
PH.CREATED_DATE_TIME,
PH.CLOSED_DATE_TIME,
PH.STATUS AS POHEADERSTATUS,
PH.SHIP_FROM,
PH.SHIP_FROM_ADDRESS1,
PH.SHIP_FROM_ADDRESS2,
PH.SHIP_FROM_ADDRESS3,
PH.SHIP_FROM_CITY,
PH.SHIP_FROM_STATE,
PH.SHIP_FROM_COUNTRY,
PH.SHIP_FROM_POSTAL_CODE,
PH.SHIP_FROM_NAME,
PH.SHIP_FROM_ATTENTION_TO,
PH.SHIP_FROM_EMAIL_ADDRESS,
PH.SHIP_FROM_PHONE_NUM,
PH.SHIP_FROM_FAX_NUM,
PH.WAREHOUSE,
PH.RECEIPT_TYPE,
NULL AS POHEADERCOMPANY,
PH.COMPANY,
PH.SOURCE_ID,
PH.SOURCE_NAME,
PH.SOURCE_ADDRESS1,
PH.SOURCE_ADDRESS2,
PH.SOURCE_ADDRESS3,
PH.SOURCE_ATTENTION_TO,
PH.SOURCE_CITY AS POHEADERSOURCECITY,
PH.SOURCE_COUNTRY,
PH.SOURCE_EMAIL_ADDRESS,
PH.SOURCE_FAX_NUM,
PH.SOURCE_PHONE_NUM,
PH.SOURCE_POSTAL_CODE,
PH.SOURCE_STATE,
PH.USER_DEF1 AS PURCHASE_ORDER_HEADER_USERDEF1,
PH.USER_DEF2 AS PURCHASE_ORDER_HEADER_USERDEF2,
PH.USER_DEF3 AS PURCHASE_ORDER_HEADER_USERDEF3,
PH.USER_DEF4 AS PURCHASE_ORDER_HEADER_USERDEF4,
PH.USER_DEF5 AS PURCHASE_ORDER_HEADER_USERDEF5,
PH.USER_DEF6 AS PURCHASE_ORDER_HEADER_USERDEF6,
PH.USER_DEF7 AS PURCHASE_ORDER_HEADER_USERDEF7,
PH.USER_DEF8 AS PURCHASE_ORDER_HEADER_USERDEF8,
PH.USER_STAMP AS POHEADERUSERSTAMP,
PH.DATE_TIME_STAMP AS POHEADERDATETIMESTAMP,
case when PH.STATUS = N'<literal:1>' then 1 else 0 end as OPEN_ORDERS, 
case when PH.STATUS = N'<literal:2>' then 1 else 0 end as CLOSED_ORDERS, 
PD.OBJECT_ID AS PODETAILOBJECTID,
PD.LINE_NUMBER AS PODETAILLINENUMBER,
PD.ITEM,
PD.COMPANY AS PODETAILCOMPANY,
PD.TOTAL_QUANTITY,
PD.OPEN_QUANTITY,
PD.QUANTITY_UM,
PD.ITEM_CATEGORY1,
PD.ITEM_CATEGORY2,
PD.ITEM_CATEGORY3,
PD.ITEM_CATEGORY4,
PD.ITEM_CATEGORY5,
PD.ITEM_CATEGORY6,
PD.ITEM_CATEGORY7,
PD.ITEM_CATEGORY8,
PD.ITEM_CATEGORY9,
PD.ITEM_CATEGORY10,
PD.ITEM_CLASS,
PD.ITEM_COLOR,
PD.ITEM_DEPARTMENT,
PD.ITEM_DESC,
PD.ITEM_DIMENSION_UM,
PD.ITEM_DIVISION,
PD.ITEM_HEIGHT,
PD.ITEM_LENGTH,
PD.ITEM_LIST_PRICE,
PD.ITEM_NET_PRICE,
PD.ITEM_SIZE,
PD.ITEM_STYLE,
PD.ITEM_WEIGHT,
PD.ITEM_WIDTH,
PD.WEIGHT_UM,
PD.USER_DEF1 AS PURCHASE_ORDER_DETAIL_USERDEF1,
PD.USER_DEF2 AS PURCHASE_ORDER_DETAIL_USERDEF2,
PD.USER_DEF3 AS PURCHASE_ORDER_DETAIL_USERDEF3,
PD.USER_DEF4 AS PURCHASE_ORDER_DETAIL_USERDEF4,
PD.USER_DEF5 AS PURCHASE_ORDER_DETAIL_USERDEF5,
PD.USER_DEF6 AS PURCHASE_ORDER_DETAIL_USERDEF6,
PD.USER_DEF7 AS PURCHASE_ORDER_DETAIL_USERDEF7,
PD.USER_DEF8 AS PURCHASE_ORDER_DETAIL_USERDEF8,
PD.USER_STAMP AS PODETAILUSERSTAMP,
PD.DATE_TIME_STAMP AS PODETAILDATETIMESTAMP,
PD.PURCHASE_ORDER_ID AS PODETAILPURCHASEORDERID,
case when PD.OBJECT_ID > 0 then 1 else 0 end as LINES,
(select top 1 RECEIPT_ID from RECEIPT_DETAIL where PURCHASE_ORDER_DETAIL_ID = pd.OBJECT_ID ) as RECEIPT_ID
FROM
PURCHASE_ORDER_HEADER PH LEFT OUTER JOIN PURCHASE_ORDER_DETAIL PD
ON PH.OBJECT_ID = PD.PURCHASE_ORDER_OBJECT_ID