CREATE VIEW METADATA_INSIGHT_WORK_VIEW
AS
select 
	wi.INTERNAL_INSTRUCTION_NUM,
	wi.INSTRUCTION_TYPE,
	wi.PARENT_INSTR,
	wi.WORK_UNIT,
	wi.SEQUENCE,
	wi.LAUNCH_NUM,
	wi.PRIORITY as WORK_INSTRUCTION_PRIORITY,
	wi.CONDITION as WORK_INSTRUCTION_CONDITION,
	wi.HOLD_CODE,
	wi.REFERENCE_ID,
	wi.REFERENCE_TYPE,
	wi.ERP_ORDER,
	wi.ERP_ORDER_LINE_NUM,
	wi.INTERNAL_NUM,
	wi.INTERNAL_LINE_NUM,
	wi.PICK_LIST_ID,
	wi.ACCOUNT,
	wi.WORK_TYPE,
	wi.WORK_GROUP,
	wi.COMPANY,
	wi.ITEM,
	wi.ITEM_DESC,
	wi.FROM_QTY,
	wi.QUANTITY,
	wi.TO_QTY,
	wi.QUANTITY_UM,
	wi.TOTAL_WEIGHT,
	wi.WEIGHT_UM,
	wi.TOTAL_VOLUME,
	wi.FROM_WHS,
	wi.TO_WHS,
	wi.VOLUME_UM,
	wi.TOTAL_VALUE,
	wi.FROM_LOC,
	wi.TO_LOC,
	wi.FROM_CHECK_DIG,
	wi.TO_CHECK_DIG,
	wi.FROM_WORK_ZONE,
	wi.TO_WORK_ZONE,
	wi.COMPLETED_BY_USER,
	wi.TEAM_ASSIGNED,
	wi.USER_ASSIGNED,
	wi.ESTIMATED_TIME,
	wi.AGING_DATE_TIME,
	wi.START_DATE_TIME,
	wi.END_DATE_TIME,
	wi.NUMBER_OF_CHILDREN,
	wi.MESSAGE_ID,
	wi.LOT,
	wi.USER_DEF1 as WORK_INSTRUCTION_USER_DEF1,
	wi.USER_DEF2 as WORK_INSTRUCTION_USER_DEF2,
	wi.USER_DEF3 as WORK_INSTRUCTION_USER_DEF3,
	wi.USER_DEF4 as WORK_INSTRUCTION_USER_DEF4,
	wi.USER_DEF5 as WORK_INSTRUCTION_USER_DEF5,
	wi.USER_DEF6 as WORK_INSTRUCTION_USER_DEF6,
	wi.USER_DEF7 as WORK_INSTRUCTION_USER_DEF7,
	wi.USER_DEF8 as WORK_INSTRUCTION_USER_DEF8,
	wi.USER_STAMP as WORK_INSTRUCTION_USER_STAMP,
	wi.PROCESS_STAMP as WORK_INSTRUCTION_PROCESS_STAMP,
	wi.DATE_TIME_STAMP as WORK_INSTRUCTION_DATE_TIME_STAMP,
	wi.EQUIPMENT_LOC,
	wi.CONVERTED_QTY,
	wi.CONVERTED_QTY_UM,
	wi.INTERNAL_NUM_TYPE,
	wi.INTERNAL_REQ_NUM,
	wi.INVENTORY_TRACKING,
	wi.LOCATING_ZONE,
	wi.FROM_TEMPL_FIELD1,
	wi.FROM_TEMPL_FIELD2,
	wi.FROM_TEMPL_FIELD3,
	wi.FROM_TEMPL_FIELD4,
	wi.FROM_TEMPL_FIELD5,
	wi.TO_TEMPL_FIELD1,
	wi.TO_TEMPL_FIELD2,
	wi.TO_TEMPL_FIELD3,
	wi.TO_TEMPL_FIELD4,
	wi.TO_TEMPL_FIELD5,
	wi.ALLOCATION_ZONE,
	wi.INTERNAL_CONTAINER_NUM,
	wi.CONTAINER_ID,
	wi.PARENT_CONTAINER_NUM,
	wi.PARENT_CONTAINER_ID,
	wi.INTERNAL_COUNT_NUM,
	wi.CYCLE_COUNT,
	wi.RELATED_WORK_UNIT,
	wi.TRANSPORT_CONT_ID,
	wi.GROUP_NUM as WORK_INSTRUCTION_GROUP_NUM,
	wi.OUTGOING_PD_LOC,
	wi.INCOMING_PD_LOC,
	wi.INVENTORY_AT_PD,
	wi.CYCLE_COUNT_GROUP_NUM,
	wi.ASSIGNMENT_ID,
	wi.LOGISTICS_UNIT,
	wi.PARENT_LOGISTICS_UNIT,
	wi.TREE_UNIT,
	wi.TREE_UNIT_ID,
	wi.LOCKED,
	wi.FROM_LOC_INV_ATTRIBUTES_ID,
	wi.TO_LOC_INV_ATTRIBUTES_ID, 
	case when wi.INSTRUCTION_TYPE = N'<literal:1>' and wi.CONDITION in (N'<literal:2>', N'<literal:3>') then 1 else 0 end as OPEN_PICKS, 
	case when wi.INSTRUCTION_TYPE = N'<literal:4>' and wi.CONDITION = N'<literal:5>' then 1 else 0 end as CLOSED_PICKS, 
	case when wi.INSTRUCTION_TYPE = N'<literal:6>' and wi.INTERNAL_NUM_TYPE NOT IN (N'<literal:7>', N'<literal:8>') then wi.QUANTITY - wi.FROM_QTY else 0 end as PICKED_QTY,  
	case when wi.INSTRUCTION_TYPE = N'<literal:9>' and wi.INTERNAL_NUM_TYPE NOT IN (N'<literal:10>', N'<literal:11>') then FROM_QTY else 0 end as OPEN_QTY,
    sh.CUSTOMER_CATEGORY1,
	sh.CUSTOMER_NAME,
	sh.SHIP_TO_NAME,
	case when wi.INSTRUCTION_TYPE = N'<literal:12>' then case when (wi.INTERNAL_NUM_TYPE = N'<literal:13>' and wi.TO_QTY > 0) then wi.TO_QTY else wi.FROM_QTY end else 0 end as CONFIRM_QTY,
	WT.LABOR_GROUP,
	ISNULL((SELECT LOCATION_CLASS FROM LOCATION WHERE LOCATION=wi.FROM_LOC AND WAREHOUSE=wi.FROM_WHS), N'<literal:14>') as FROM_LOC_CLASS,
	wi.SRC_IDENTIFIER
from
	WORK_INSTRUCTION_VIEW wi
	LEFT OUTER JOIN WORK_TYPE WT ON wi.WORK_TYPE = WT.WORK_TYPE
	LEFT OUTER JOIN SHIPMENT_HEADER sh 
ON wi.INTERNAL_NUM=sh.INTERNAL_SHIPMENT_NUM
AND wi.INTERNAL_NUM_TYPE = N'<literal:15>'