	set @newAllocReqNum = SCOPE_IDENTITY();

	/* [comment omitted] */
	UPDATE SHIPMENT_ALLOC_REQUEST
	SET	CONVERTED_ALLOC_QTY = (CONVERTED_ALLOC_QTY / ALLOCATED_QTY) * (ALLOCATED_QTY - @qty),
		ALLOCATED_QTY = ALLOCATED_QTY - @qty,
		PROCESS_STAMP = N'<literal:1>',
		DATE_TIME_STAMP = GETUTCDATE(),
		USER_STAMP = @userName
	WHERE INTERNAL_SHIP_ALLOC_NUM = @newAllocReqNum
	AND ALLOCATED_QTY >= @qty;
	
	if (@@ERROR <> 0) return -1;
		
	/* [comment omitted] */
	UPDATE SHIPMENT_ALLOC_REQUEST
	SET	CONVERTED_ALLOC_QTY = (CONVERTED_ALLOC_QTY / ALLOCATED_QTY) * (ALLOCATED_QTY - (ALLOCATED_QTY - @qty)),
		ALLOCATED_QTY = (ALLOCATED_QTY - (ALLOCATED_QTY - @qty)),
		PROCESS_STAMP = N'<literal:2>',
		DATE_TIME_STAMP = GETUTCDATE(),
		USER_STAMP = @userName
	WHERE INTERNAL_SHIP_ALLOC_NUM = @allocReqNum;
	if (@@ERROR <> 0) return -1;	

