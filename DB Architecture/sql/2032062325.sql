CREATE VIEW SHIPMENT_HEADER_VIEW   
AS   
SELECT   
 sh.INTERNAL_SHIPMENT_NUM,  
 sh.WAREHOUSE,  
 sh.SHIPPING_LOAD_NUM,  
 sh.SHIPMENT_ID,  
 sh.LAUNCH_STEP,  
 sh.TRAILING_STS,  
 sh.TRAILING_STS_DATE,  
 sh.TRAILING_STS_FAILED,  
 sh.ORDER_TYPE,  
 sh.CONSOLIDATED,  
 sh.LEADING_STS,  
 sh.LEADING_STS_DATE,  
 sh.CARRIER,  
 sh.LEADING_STS_FAILED,  
 sh.COMPANY,  
 sh.CARRIER_SERVICE,  
 sh.CARRIER_GROUP,  
 sh.CARRIER_TYPE,  
 sh.FREIGHT_TERMS,  
 sh.LIABILITY_TERMS,  
 sh.CUSTOMER,  
 sh.SHIP_TO,  
 sh.ROUTE,  
 sh.STOP,  
 sh.SHIP_TO_ADDRESS1,  
 sh.CUSTOMER_NAME,  
 sh.SHIP_TO_ADDRESS2,  
 sh.SHIP_TO_ADDRESS3,  
 sh.SHIP_TO_CITY,  
 sh.SHIP_TO_STATE,  
 sh.SHIP_TO_COUNTRY,  
 sh.SHIP_TO_POSTAL_CODE,  
 sh.SHIP_TO_PHONE_NUM,  
 sh.SHIP_TO_FAX_NUM,  
 ISNULL(sc_totals.TOTAL_CONTAINERS,0) AS TOTAL_CONTAINERS,  
 ISNULL(sd_totals.TOTAL_LINES,0) AS TOTAL_LINES,  
 sh.CUSTOMER_ADDRESS1,  
 sh.LAUNCH_NUM,  
 sh.WEIGHT_UM,  
 CASE WHEN (ISNULL(sc_totals.TOTAL_CONTAINERS,0) = 0) AND  
    ( WEIGHT_ENTERED IS NOT NULL) AND (WEIGHT_ENTERED >0 )  
   THEN WEIGHT_ENTERED  
   WHEN ISNULL(sc_totals.TOTAL_CONTAINERS,0) > 0   
   THEN ISNULL(sc_totals.TOTAL_WEIGHT,0)   
   ELSE ISNULL(sd_totals.TOTAL_WEIGHT,0)  
 END AS TOTAL_WEIGHT,  
 CASE WHEN  (ISNULL(sc_totals.TOTAL_CONTAINERS,0) = 0) AND   
    VOLUME_ENTERED IS NOT NULL AND VOLUME_ENTERED >0   
   THEN VOLUME_ENTERED  
   WHEN ISNULL(sc_totals.TOTAL_CONTAINERS,0) > 0   
   THEN ISNULL(sc_totals.TOTAL_VOLUME,0)   
   ELSE ISNULL(sd_totals.TOTAL_VOLUME,0)   
 END AS TOTAL_VOLUME,  
 sh.VOLUME_UM,  
 sh.ROUTING_CODE,  
 CASE WHEN  (ISNULL(sc_totals.TOTAL_CONTAINERS,0) = 0) AND   
    VALUE_ENTERED IS NOT NULL AND VALUE_ENTERED >0   
   THEN VALUE_ENTERED  
   WHEN ISNULL(sc_totals.TOTAL_CONTAINERS,0) > 0   
   THEN ISNULL(sc_totals.TOTAL_VALUE,0)   
   ELSE ISNULL(sd_totals.TOTAL_VALUE,0)   
 END AS TOTAL_VALUE,  
 sh.SINGLE_ITEM_CARTONS,  
 sh.USER_DEF1,  
 sh.USER_DEF2,  
 sh.PRIORITY,  
 sh.USER_DEF3,  
 sh.USER_DEF4,  
 sh.USER_DEF5,  
 sh.USER_DEF6,  
 sh.USER_DEF7,  
 sh.MANUALLY_ENTERED,  
 sh.USER_DEF8,  
 sh.USER_DEF9, 
 sh.USER_DEF10,
 sh.USER_DEF11,
 sh.USER_DEF12,
 sh.USER_DEF13,
 sh.USER_DEF14,
 sh.USER_DEF15,
 sh.USER_DEF16,
 sh.USER_DEF17_DATE_TIME,
 sh.USER_DEF18_DATE_TIME,
 sh.USER_DEF19_DATE_TIME,
 sh.USER_DEF20_DATE_TIME,
 sh.USER_STAMP,  
 sh.PROCESS_STAMP,  
 sh.DATE_TIME_STAMP,  
 sh.BOL_NUM_ALPHA,  
 sh.PRO_NUM_ALPHA,  
 sh.CUSTOMER_ADDRESS3,  
 sh.CUSTOMER_ADDRESS2,  
 sh.CUSTOMER_ATTENTION_TO,  
 sh.CUSTOMER_CITY,  
 sh.CUSTOMER_STATE,  
 sh.CUSTOMER_COUNTRY,  
 sh.CUSTOMER_POSTAL_CODE,  
 sh.CUSTOMER_PHONE_NUM,  
 sh.CUSTOMER_FAX_NUM,  
 sh.CUSTOMER_EMAIL_ADDRESS,  
 sh.SHIP_TO_NAME,  
 sh.SHIP_TO_ATTENTION_TO,  
 sh.SHIP_TO_EMAIL_ADDRESS,  
 sh.REQUESTED_DELIVERY_DATE,  
 sh.REQUESTED_DELIVERY_TYPE,  
 sh.SCHEDULED_SHIP_DATE,  
 sh.PLANNED_SHIP_DATE,  
 sh.ACTUAL_SHIP_DATE_TIME,  
 sh.PLANNED_DELIVERY_DATE_TIME,  
 sh.ACTUAL_DELIVERY_DATE_TIME,  
 ISNULL(sd_totals.TOTAL_QTY,0) AS TOTAL_QTY,  
 sh.QUANTITY_UM,  
 sh.TOTAL_FREIGHT_CHARGE,  
 sh.BASE_FREIGHT_CHARGE,  
 sh.FREIGHT_DISCOUNT,  
 sh.ACCESSORIAL_CHARGE,  
 sh.CONSOLIDATION_ALLOWED,  
 sh.INTERMEDIATE_CONSIGNEE,  
 sh.INTERMEDIATE_NAME,  
 sh.INTERMEDIATE_ADDRESS1,  
 sh.INTERMEDIATE_ADDRESS2,  
 sh.INTERMEDIATE_ADDRESS3,  
 sh.INTERMEDIATE_ATTENTION_TO,  
 sh.INTERMEDIATE_CITY,  
 sh.INTERMEDIATE_STATE,  
 sh.INTERMEDIATE_COUNTRY,  
 sh.INTERMEDIATE_POSTAL_CODE,  
 sh.INTERMEDIATE_PHONE_NUM,  
 sh.INTERMEDIATE_FAX_NUM,  
 sh.INTERMEDIATE_EMAIL_ADDRESS,  
 sh.FREIGHT_BILL_TO,  
 sh.FREIGHT_BILL_TO_NAME,  
 sh.FREIGHT_BILL_TO_ADDRESS1,  
 sh.FREIGHT_BILL_TO_ADDRESS2,  
 sh.FREIGHT_BILL_TO_ADDRESS3,  
 sh.FREIGHT_BILL_TO_ATTENTION_TO,  
 sh.FREIGHT_BILL_TO_CITY,  
 sh.FREIGHT_BILL_TO_STATE,  
 sh.FREIGHT_BILL_TO_COUNTRY,  
 sh.FREIGHT_BILL_TO_POSTAL_CODE,  
 sh.FREIGHT_BILL_TO_PHONE_NUM,  
 sh.FREIGHT_BILL_TO_FAX_NUM,  
 sh.FREIGHT_BILL_TO_EMAIL_ADDRESS,  
 sh.ERP_ORDER,  
 sh.INTERNAL_ORDER_NUM,  
 sh.EXPORT_TAX_ID,  
 sh.PARTIES,  
 sh.LOADING_PIER,  
 sh.TRANSPORTATION_MODE,  
 sh.EXPORT_PORT,  
 sh.UNLOADING_PORT,  
 sh.CONTAINERIZED,  
 sh.FTZ,  
 sh.VALIDATED_LICENSE,  
 sh.LICENSE_EXP_DATE,  
 sh.ECCN,  
 sh.AUTHORIZED_EMPL_NAME,  
 sh.AUTHORIZED_EMPL_TITLE,  
 sh.UPLOAD_INTERFACE_BATCH,  
 sh.CUSTOMER_RESIDENTIAL_FLAG,  
 sh.SHIPTO_RESIDENTIAL_FLAG,  
 sh.REJECTION_NOTE,  
 sh.INTERFACE_RECORD_ID,  
 sh.CUSTOMER_CATEGORY1,  
 sh.CUSTOMER_CATEGORY2,  
 sh.CUSTOMER_CATEGORY3,  
 sh.CUSTOMER_CATEGORY4,  
 sh.CUSTOMER_CATEGORY5,  
 sh.CUSTOMER_CATEGORY6,  
 sh.CUSTOMER_CATEGORY7,  
 sh.CUSTOMER_CATEGORY8,  
 sh.CUSTOMER_CATEGORY9,  
 sh.CUSTOMER_CATEGORY10,  
 sh.CONSOLIDATION_DOCK_LOC_AREA,  
 sh.CONSOLIDATION_DOCK_LOC_POS,   
 sh.PROCESS_TYPE,  
 sh.CREATION_PROCESS_STAMP,  
 sh.CREATION_DATE_TIME_STAMP,  
 sh.IMMEDIATE_NEEDS_NOTE,  
 sh.ALLOCATE_COMPLETE,  
 sh.ALTERNATE_EMAIL_ADDRESS,  
 sh.STOP_SEQUENCE,  
 sh.INTERNAL_CARRIER_NUM,  
 sh.STORE_DISTRIBUTION,  
 sh.TOTAL_LBR_ESTIMATE,  
 sh.LOCKED,
 sh.SHIPPER_CODE,
 sh.IN_DELETION, 
 sh.INVENTORY_LOAD_CONFIRMED, 
 sh.LAST_STATUS_UPLOADED ,
 sh.Weight_Entered,
 sh.Volume_Entered,
 sh.Value_Entered
 FROM SHIPMENT_HEADER sh WITH (NOLOCK)  
  LEFT OUTER JOIN  
    (SELECT  INTERNAL_SHIPMENT_NUM,   
     COUNT(INTERNAL_SHIPMENT_LINE_NUM) AS TOTAL_LINES,   
     SUM(ISNULL(TOTAL_WEIGHT,0)) AS TOTAL_WEIGHT,   
     SUM(ISNULL(TOTAL_VOLUME,0)) AS TOTAL_VOLUME,   
     SUM(ISNULL(VALUE,0)) AS TOTAL_VALUE,   
     SUM(ISNULL(TOTAL_QTY,0)) AS TOTAL_QTY  
    FROM SHIPMENT_DETAIL WITH (NOLOCK)  
    GROUP BY INTERNAL_SHIPMENT_NUM) sd_totals   
  ON sh.INTERNAL_SHIPMENT_NUM = sd_totals.INTERNAL_SHIPMENT_NUM  
  LEFT OUTER JOIN  
    (SELECT   
     INTERNAL_SHIPMENT_NUM,   
     COUNT(INTERNAL_CONTAINER_NUM) AS TOTAL_CONTAINERS,   
     SUM(ISNULL(WEIGHT,0)) AS TOTAL_WEIGHT,   
     SUM(ISNULL(VOLUME,0)) AS TOTAL_VOLUME,   
     SUM(ISNULL(VALUE,0)) AS TOTAL_VALUE  
     FROM SHIPPING_CONTAINER WITH (NOLOCK)  
    WHERE PARENT IS NULL  
    GROUP BY INTERNAL_SHIPMENT_NUM) sc_totals   
  ON sh.INTERNAL_SHIPMENT_NUM = sc_totals.INTERNAL_SHIPMENT_NUM;