CREATE VIEW METADATA_INSIGHT_LABOR_ACTIVITY_VIEW
AS
SELECT
LD.INTERNAL_DETAIL_NUM,
LD.ACTIVITY_TYPE,
LD.ACTIVITY_SCREEN,
LD.WAREHOUSE,
LD.WORK_GROUP,
LD.WORK_TEAM,
LD.USER_NAME,
LD.COMPANY,
LD.EQUIPMENT_TYPE,
LD.START_DATE_TIME,
LD.END_DATE_TIME,
LD.TOTAL_ACTUAL_TIME,
LD.TOTAL_TRANSACTIONS,
LD.TOTAL_QUANTITY,
LD.QUANTITY_UM,
LD.TOTAL_LABOR_COST,
LD.TOTAL_WEIGHT,
LD.WEIGHT_UM,
LD.TOTAL_VOLUME,
LD.VOLUME_UM,
LD.TOTAL_VALUE,
LD.CLOSED,
LD.LABOR_TYPE,
LD.USER_DEF1 AS UD_LABORMANAGEMENTDETAIL1,
LD.USER_DEF2 AS UD_LABORMANAGEMENTDETAIL2,
LD.USER_DEF3 AS UD_LABORMANAGEMENTDETAIL3,
LD.USER_DEF4 AS UD_LABORMANAGEMENTDETAIL4,
LD.USER_DEF5 AS UD_LABORMANAGEMENTDETAIL5,
LD.USER_DEF6 AS UD_LABORMANAGEMENTDETAIL6,
LD.USER_DEF7 AS UD_LABORMANAGEMENTDETAIL7,
LD.USER_DEF8 AS UD_LABORMANAGEMENTDETAIL8,
LD.USER_STAMP,
LD.PROCESS_STAMP,
LD.DATE_TIME_STAMP,
LD.PROCESS_TYPE,
LD.MANUAL,
LD.LABOR_GROUP,
LD.ACTUAL_RATE,
LD.GOAL_RATE,
LD.GOAL_QUANTITY,
LD.PERCENT_OF_GOAL,
LD.WAVE_NUM,
LD.DEVICE_TYPE,
LD.FROM_LOCATION,
LD.INTERNAL_NUM,
LD.ITEM,
LD.LICENSE_PLATE,
LD.REFERENCE_ID,
LD.SESSION_ID,
LD.SHIFT,
LD.TO_LOCATION,
LD.WORK_UNIT,
LD.CONTAINER_ID,
LD.INTERNAL_CONTAINER_NUM,
(CASE WHEN LD.ACTUAL_RATE > 0 THEN (LD.TOTAL_QUANTITY/LD.ACTUAL_RATE) ELSE 0 END) as TOTALTIME,
(CASE WHEN LD.ACTUAL_RATE > 0 AND LD.TOTAL_QUANTITY > 0 THEN (LD.TOTAL_QUANTITY/(LD.TOTAL_QUANTITY/LD.ACTUAL_RATE)) ELSE 0 END) as AVERAGERATE,
LD.CONSOLIDATED,
LD.WAREHOUSE_DAY
FROM
LABOR_MANAGEMENT_DETAIL LD
