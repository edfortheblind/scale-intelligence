DECLARE cArchiveCreate CURSOR FAST_FORWARD READ_ONLY FOR
SELECT TABLE_NAME, NULL AS IDENTIFIER, NULL AS SYSTEM_CREATED
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
	AND TABLE_NAME NOT LIKE '%[0-9]%'
	AND TABLE_NAME NOT LIKE N'%DSCSA%'
	AND TABLE_NAME NOT LIKE N'%' + UPPER(LEFT(DB_NAME(), 4)) + N'%'
    AND (TABLE_NAME LIKE 'AR[_]%'
		OR TABLE_NAME IN (SELECT TABLE_NAME COLLATE SQL_LATIN1_GENERAL_CP1_CI_AS FROM @NewArchivePrefTables))
UNION ALL
SELECT CASE 
	WHEN RECORD_TYPE = N'HIST PROC' THEN N'PROCESS_HISTORY_' + LEFT(GCD.IDENTIFIER, 34) 
	WHEN RECORD_TYPE = N'HIST TR TY' THEN N'TRANSACTION_HISTORY_' + LEFT(GCD.IDENTIFIER, 30) END COLLATE SQL_Latin1_General_CP1_CI_AS AS TABLE_NAME, 
	GCD.IDENTIFIER, GCD.SYSTEM_CREATED
FROM GENERIC_CONFIG_DETAIL GCD WITH(NOLOCK)
WHERE RECORD_TYPE IN (N'HIST PROC', N'HIST TR TY')
ORDER BY TABLE_NAME
OPEN cArchiveCreate
FETCH NEXT FROM cArchiveCreate INTO @ARtableName, @IDENTIFIER, @SYSTEMCREATED
 
WHILE @@FETCH_STATUS = 0 
BEGIN
    /* SET ARHISTTABLENAME TO TRIM OFF _170 FOR EXAMPLE FROM PROCESS_HISTORY_170 */
    SET @ARHistTableName = (SELECT LEFT(@ARtableName, CHARINDEX(N'_', @ARtableName, 14)-1) 
        WHERE @ARtableName LIKE N'PROCESS[_]HISTORY[_]%'
            OR @ARtableName LIKE N'TRANSACTION[_]HISTORY[_]%');
    SET @DOPATH = (SELECT TOP 1 DO_PATH FROM ARCHIVE_PREFERENCES WHERE TABLE_DO_NAME = @ARHistTableName AND @ARHistTableName IN (N'PROCESS_HISTORY', N'TRANSACTION_HISTORY'));
    /* SET @stArchiveID TO THE MATCHING ARCHIVE_ID IF THE RECORD ALREADY EXISTS */
    SET @stArchiveID = (SELECT ARCHIVE_ID FROM ARCHIVE_PREFERENCES WHERE ARCHIVE_NAME = @ARtableName);

    /* IF THE ARCHIVE PREFERENCE TO BE CREATED DOES NOT ALREADY EXIST, CREATE IT */
    IF @stArchiveID IS NULL  
    BEGIN
        IF (SELECT ARCHIVE_ID FROM ARCHIVE_PREFERENCES WITH(NOLOCK) 
                WHERE ISNUMERIC(CAST(ARCHIVE_ID AS VARCHAR)) = 1 
                AND CAST(CASE WHEN ARCHIVE_ID NOT LIKE N'%-%' THEN ARCHIVE_ID ELSE 0 END AS INT) = 5000) IS NULL
            SET @stArchiveID = 5000;
        ELSE
        BEGIN
            SET @stArchiveID = (SELECT TOP 1 CAST(T.ARCHIVE_ID AS INT) + 1 AS NEXT_AVAILABLE_NUMBER
                                FROM (
                                    SELECT 
                                        ARCHIVE_ID,
                                        LEAD(CAST(ARCHIVE_ID AS INT)) OVER (ORDER BY ARCHIVE_ID) AS NEXT_NUMBER
                                    FROM ARCHIVE_PREFERENCES
                                    WHERE ISNUMERIC(CAST(ARCHIVE_ID AS VARCHAR)) = 1
                                        AND ARCHIVE_ID NOT LIKE N'%-%'
                                        AND CAST(CASE WHEN ARCHIVE_ID NOT LIKE N'%-%' THEN ARCHIVE_ID ELSE 0 END AS INT) BETWEEN 5000 AND 9999
                                ) AS T
                                WHERE T.NEXT_NUMBER > CAST(T.ARCHIVE_ID AS INT) + 1
                                ORDER BY T.ARCHIVE_ID);

            IF @stArchiveID IS NULL
            BEGIN
                SET @stArchiveID = (SELECT CONVERT(NVARCHAR, MAX(
                CASE
                    WHEN ISNUMERIC(CAST(ARCHIVE_ID AS VARCHAR)) = 1
                            AND CAST(ARCHIVE_ID AS INT) BETWEEN 5000 AND 9999
                    THEN CAST(ARCHIVE_ID AS INT)  /* INCREMENT IF BETWEEN 5000 AND 9999 */
                    ELSE 4999 /* DEFAULT TO 4999 IF OUTSIDE THE RANGE */
                END + 1
                ))
                FROM ARCHIVE_PREFERENCES)
            END
        END

        IF (@ARtableName LIKE 'AR[_]%' 
			AND (EXISTS (SELECT N'%' FROM SYSTEM_CONFIG_DETAIL 
					WHERE DESCRIPTION = N'MAS DataSave Tier 2?' 
					AND (SYSTEM_VALUE = N'N' 
					OR USER_DEF4 = N'N')) /* AND NEW CONFIG VALUE FOR MAS_DATASAVE_TIER2 = N */
				OR NOT EXISTS (SELECT N'%' FROM SYSTEM_CONFIG_DETAIL 
					WHERE DESCRIPTION = N'MAS DataSave Tier 2?')
				OR (SELECT @@SERVERNAME) IN (SELECT DB_SERVER FROM @NonProdServerList)))	
        BEGIN
            SET @DaysHist = CASE WHEN @ARtableName IN (N'AR_WORK_INSTRUCTION', N'AR_IA_WORK_INSTRUCTION')
                    AND (SELECT ISNULL(USER_DEF4, N'!') FROM ARCHIVE_PREFERENCES WITH(NOLOCK) WHERE ARCHIVE_NAME = N'Work Instruction') <> N'Y'
                THEN @DaysHistDefaultValue
                ELSE @DaysHistARTablesDefault
                END
            SET @SaveData = N'N';
            SET @Active = @AR_Active;
            SET @DataStorageType = N'DEFAULT';
        END
        ELSE IF (@ARtableName LIKE 'AR[_]%' AND 
            EXISTS (SELECT N'%' FROM SYSTEM_CONFIG_DETAIL 
                WHERE DESCRIPTION = N'MAS DataSave Tier 2?' 
                AND SYSTEM_VALUE = N'Y' 
                AND USER_DEF4 = N'Y')) /* AND NEW CONFIG VALUE FOR MAS_DATASAVE_TIER2 = Y */
        BEGIN
            SET @DaysHist = CASE WHEN @ARtableName IN (N'AR_WORK_INSTRUCTION', N'AR_IA_WORK_INSTRUCTION')
                    AND (SELECT ISNULL(USER_DEF4, N'!') FROM ARCHIVE_PREFERENCES WITH(NOLOCK) WHERE ARCHIVE_NAME = N'Work Instruction') <> N'Y'
                THEN @DaysHistDefaultValue
                ELSE @DaysHistARTablesDefault
                END;
            SET @SaveData = N'Y';
            SET @Active = @AR_Active;
            SET @DataStorageType = N'MS SQL';
        END
        ELSE IF @ARtableName IN (SELECT TABLE_NAME FROM @NewArchivePrefTables)
        BEGIN
            SET @DaysHist = @DaysHistMinimumValue;
            SET @SaveData = N'N';
            SET @Active = N'Y';
            SET @DataStorageType = N'DEFAULT';
        END
        ELSE IF @ARHistTableName IN (N'PROCESS_HISTORY')
        BEGIN
            SET @DaysHist = CASE WHEN @ARtableName IN (SELECT ARCHIVE_NAME FROM @DaysHistArchivePreferencesMinimum)
                            THEN @DaysHistMinimumValue
                            WHEN @IDENTIFIER IN (SELECT IDENTIFIER FROM @ProcessHistoryTypesToSave) OR @SYSTEMCREATED = N'N'
                            THEN @DaysHistDefaultValue
                            ELSE @DaysHistPurgeValue
                            END
            SET @SaveData = CASE WHEN (@IDENTIFIER IN (SELECT IDENTIFIER FROM @ProcessHistoryTypesToSave) OR @SYSTEMCREATED = N'N')
                                    AND (SELECT @@SERVERNAME) NOT IN (SELECT DB_SERVER FROM @NonProdServerList)
                            THEN N'Y'
                            ELSE N'N'
                            END
            SET @Active = N'Y';
            SET @DataStorageType = N'DEFAULT';
        END
        ELSE IF @ARHistTableName IN (N'TRANSACTION_HISTORY')
        BEGIN
            SET @DaysHist = CASE WHEN @ARtableName IN (SELECT ARCHIVE_NAME FROM @DaysHistArchivePreferencesMinimum)
                            THEN @DaysHistMinimumValue
                            WHEN @IDENTIFIER IN (SELECT IDENTIFIER FROM @TransactionHistoryTypesToPurge)
                                OR @IDENTIFIER IN (SELECT IDENTIFIER FROM @TransactionHistoryTypesNonDefault)
                            THEN @DaysHistPurgeValue
                            ELSE @DaysHistDefaultValue
                            END
            SET @SaveData = CASE WHEN @IDENTIFIER IN (SELECT IDENTIFIER FROM @TransactionHistoryTypesToPurge)
                                    OR (SELECT @@SERVERNAME) IN (SELECT DB_SERVER FROM @NonProdServerList)
                            THEN N'N'
                            ELSE N'Y'
                            END
            SET @Active = N'Y';
            SET @DataStorageType = N'DEFAULT';
