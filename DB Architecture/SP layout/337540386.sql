                    AND P.ROWS > 0
                GROUP BY T.NAME, P.ROWS)
UNION ALL
SELECT TOP 1 CASE 
	WHEN NOT EXISTS (SELECT N'%' FROM ARCHIVE_PREFERENCES WITH(NOLOCK) WHERE ARCHIVE_NAME LIKE N'PROCESS[_]HISTORY[_]%' AND SAVE_DATA = N'Y') 
