	WHEN NOT EXISTS (SELECT N'%' FROM ARCHIVE_PREFERENCES WITH(NOLOCK) WHERE ARCHIVE_NAME LIKE N'TRANSACTION[_]HISTORY[_]%' AND SAVE_DATA = N'Y') 
